/* Master Scanner dashboard
   Compatible with resultdow.json / resultwgat.json generated by
   DOW_JSON.py and WGAT_JSON.py in this repository.
*/

const DATA = { dow: [], wgat: [] };
const SORT = {
  dow: { key: "stock", dir: "asc" },
  wgat: { key: "stock", dir: "asc" }
};
const EXPANDED = { dow: new Set(), wgat: new Set() };

const FIBS = [
  ["23pct", "23%"],
  ["38pct", "38%"],
  ["50pct", "50%"],
  ["618pct", "61.8%"],
  ["78pct", "78%"]
];

const FILES = {
  dow: "resultdow.json",
  wgat: "resultwgat.json"
};

document.addEventListener("DOMContentLoaded", init);

async function init() {
  wireTabs();
  wireFilters();
  wireSorting();

  try {
    const [dowRaw, wgatRaw] = await Promise.all([
      fetchJSON(FILES.dow),
      fetchJSON(FILES.wgat)
    ]);

    DATA.dow = normalizeDow(dowRaw);
    DATA.wgat = normalizeWgat(wgatRaw);

    updateMeta(dowRaw, wgatRaw);
    renderTable("dow");
    renderTable("wgat");
    renderTicker("dow");
  } catch (err) {
    console.error("Scanner data load error:", err);
    showFetchError(err);
  }
}

async function fetchJSON(file) {
  const url = `${file}?v=${Date.now()}`;
  const res = await fetch(url, { cache: "no-store" });
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return await res.json();
}

/* =========================================================
   DATA NORMALIZATION
   ========================================================= */
function normalizeDow(raw) {
  // New DOW_JSON.py format:
  // { timeframes: { "Daily": { results: [...] }, ... } }
  const rows = [];
  const timeframes = raw?.timeframes || {};

  Object.entries(timeframes).forEach(([tf, block]) => {
    (block?.results || []).forEach(r => {
      rows.push({
        stock: String(r.Stock ?? r.stock ?? ""),
        timeframe: String(r.Timeframe ?? r.timeframe ?? tf),
        trend_bucket: String(r["Trend Bucket"] ?? r.trend_bucket ?? ""),
        last_close: num(r.Close ?? r["Last Close"] ?? r.last_close),
        last_date: r["Scan Date"] ?? r["Last Candle"] ?? r.last_date ?? null,
        "23pct_bull": bool(r["23% Bull"], r["23pct_bull"]),
        "38pct_bull": bool(r["38% Bull"], r["38pct_bull"]),
        "50pct_bull": bool(r["50% Bull"], r["50pct_bull"]),
        "618pct_bull": bool(r["61.8% Bull"], r["618pct_bull"]),
        "78pct_bull": bool(r["78% Bull"], r["78pct_bull"]),
        "23pct_bear": bool(r["23% Bear"], r["23pct_bear"]),
        "38pct_bear": bool(r["38% Bear"], r["38pct_bear"]),
        "50pct_bear": bool(r["50% Bear"], r["50pct_bear"]),
        "618pct_bear": bool(r["61.8% Bear"], r["618pct_bear"]),
        "78pct_bear": bool(r["78% Bear"], r["78pct_bear"]),
        "23pct_up": num(r["23% Up"] ?? r["23pct_up"]),
        "38pct_up": num(r["38% Up"] ?? r["38pct_up"]),
        "50pct_up": num(r["50% Up"] ?? r["50pct_up"]),
        "618pct_up": num(r["61.8% Up"] ?? r["618pct_up"]),
        "78pct_up": num(r["78% Up"] ?? r["78pct_up"]),
        "23pct_down": num(r["23% Down"] ?? r["23pct_down"]),
        "38pct_down": num(r["38% Down"] ?? r["38pct_down"]),
        "50pct_down": num(r["50% Down"] ?? r["50pct_down"]),
        "618pct_down": num(r["61.8% Down"] ?? r["618pct_down"]),
        "78pct_down": num(r["78% Down"] ?? r["78pct_down"])
      });
    });
  });

  return rows;
}

function normalizeWgat(raw) {
  // New WGAT_JSON.py format:
  // { scan: { results: [...] } }
  const source = raw?.scan?.results || raw?.results || [];
  return source.map(r => ({
    stock: String(r.Stock ?? r.stock ?? ""),
    category_1: String(r["Category 1"] ?? r.category_1 ?? "No Clear Trend"),
    last_close: num(r.Close ?? r["Last Close"] ?? r.last_close),
    last_date: r["Scan Date"] ?? r["Last Candle"] ?? r.last_date ?? null,
    daily_macd: r["Daily MACD"] ?? r.daily_macd ?? null,
    previous_daily_macd: r["Previous Daily MACD"] ?? r.previous_daily_macd ?? null,
    weekly_macd: r["Weekly MACD"] ?? r.weekly_macd ?? null,
    monthly_macd: r["Monthly MACD"] ?? r.monthly_macd ?? null,
    bullish_momentum: bool(r["Bullish Momentum"], r.bullish_momentum),
    bearish_momentum: bool(r["Bearish Momentum"], r.bearish_momentum),
    bullish_swing: bool(r["Bullish Swing"], r.bullish_swing),
    bearish_swing: bool(r["Bearish Swing"], r.bearish_swing),
    rsi: num(r.RSI ?? r.rsi),
    adx: num(r.ADX ?? r.adx)
  }));
}

function bool(...values) {
  for (const v of values) if (v !== undefined && v !== null) return v === true || v === 1 || v === "true";
  return false;
}

function num(v) {
  if (v === undefined || v === null || v === "") return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
}

/* =========================================================
   META / ERROR
   ========================================================= */
function updateMeta(dow, wgat) {
  document.getElementById("metaLive").textContent = "data loaded";
  const genAt = dow?.generated_at || wgat?.generated_at;
  const scanDate =
    dow?.scan_date ||
    wgat?.scan?.scan_date ||
    Object.values(dow?.timeframes || {}).find(x => x?.scan_date)?.scan_date ||
    "—";

  document.getElementById("metaDate").textContent =
    `Scan date: ${formatDate(scanDate)} · generated ${genAt ? new Date(genAt).toLocaleString() : "—"}`;
}

function showFetchError(err) {
  const message = `
    <div class="icon">⚠</div>
    <h3>Couldn't load scan data</h3>
    <p>The dashboard could not load <code>resultdow.json</code> and/or <code>resultwgat.json</code>.</p>
    <p class="error-detail"><code>${escapeHTML(err.message || String(err))}</code></p>
    <p>Both files must be in the same <code>wgat/</code> folder as <code>index.html</code>.</p>
    <button class="btn primary" onclick="location.reload()">Reload Data</button>
  `;
  ["dowState", "wgatState"].forEach(id => {
    const el = document.getElementById(id);
    el.innerHTML = message;
    el.classList.remove("hidden");
  });
  document.getElementById("metaLive").textContent = "no data";
}

/* =========================================================
   TABS
   ========================================================= */
function wireTabs() {
  document.querySelectorAll(".tab-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      document.querySelectorAll(".tab-btn").forEach(b => {
        b.classList.remove("active");
        b.setAttribute("aria-selected", "false");
      });
      btn.classList.add("active");
      btn.setAttribute("aria-selected", "true");
      const tab = btn.dataset.tab;
      document.querySelectorAll(".tab-panel").forEach(p => p.classList.add("hidden"));
      document.getElementById(`tab-${tab}`).classList.remove("hidden");
      renderTicker(tab);
    });
  });
}

