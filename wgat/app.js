function getDowFiltered() {
  const tf = document.getElementById("dowTimeframe").value;
  const trend = document.getElementById("dowTrend").value;
  const fib = document.getElementById("dowFib").value;
  const q = document.getElementById("dowSearch").value.trim().toUpperCase();

  return DATA.dow.filter(r => {
    if (tf !== "All" && r.timeframe !== tf) return false;
    if (trend !== "All" && r.trend_bucket !== trend) return false;
    if (fib !== "All" && r[fib] !== true) return false;
    if (q && !r.stock.toUpperCase().includes(q)) return false;
    return true;
  });
}

function getWgatFiltered() {
  const cat1 = document.getElementById("wgatCat1").value;
  const cat2 = document.getElementById("wgatCat2").value;
  const q = document.getElementById("wgatSearch").value.trim().toUpperCase();

  return DATA.wgat.filter(r => {
    if (cat1 !== "All" && r.category_1 !== cat1) return false;
    if (cat2 !== "All" && r[cat2] !== true) return false;
    if (q && !r.stock.toUpperCase().includes(q)) return false;
    return true;
  });
}

/* =========================================================
   SORTING
   ========================================================= */
function wireSorting() {
  document.querySelectorAll("#dowTable th.sortable").forEach(th => th.addEventListener("click", () => toggleSort("dow", th)));
  document.querySelectorAll("#wgatTable th.sortable").forEach(th => th.addEventListener("click", () => toggleSort("wgat", th)));
}

function toggleSort(scope, th) {
  const key = th.dataset.key;
  const s = SORT[scope];
  if (s.key === key) s.dir = s.dir === "asc" ? "desc" : "asc";
  else { s.key = key; s.dir = "asc"; }
  renderTable(scope);
}

function applySort(rows, scope) {
  const { key, dir } = SORT[scope];
  const mult = dir === "asc" ? 1 : -1;
  return [...rows].sort((a, b) => {
    const av = a[key], bv = b[key];
    if (av == null && bv == null) return 0;
    if (av == null) return 1;
    if (bv == null) return -1;
    if (typeof av === "string") return av.localeCompare(String(bv)) * mult;
    return (av - bv) * mult;
  });
}

function updateSortHeaders(tableId, scope) {
  document.querySelectorAll(`#${tableId} th.sortable`).forEach(th => {
    th.classList.remove("sorted-asc", "sorted-desc");
    if (th.dataset.key === SORT[scope].key) {
      th.classList.add(SORT[scope].dir === "asc" ? "sorted-asc" : "sorted-desc");
    }
  });
}

/* =========================================================
   DOW TABLE
   ========================================================= */
function renderDow() {
  const body = document.getElementById("dowBody");
  const state = document.getElementById("dowState");
  body.innerHTML = "";

  let rows = applySort(getDowFiltered(), "dow");
  updateSortHeaders("dowTable", "dow");
  document.getElementById("dowCount").innerHTML = `<b>${rows.length}</b> rows`;

  if (!rows.length) {
    state.classList.remove("hidden");
    state.innerHTML = emptyState("No stocks match these filters", "Try All Timeframes or widen the trend filter.");
    return;
  }
  state.classList.add("hidden");

  const frag = document.createDocumentFragment();
  rows.forEach(r => {
    const id = `${r.stock}__${r.timeframe}`;
    const tr = document.createElement("tr");
    if (EXPANDED.dow.has(id)) tr.classList.add("expanded");
    tr.innerHTML = `
      <td><div class="cell-stock"><span class="stock-ticker">${escapeHTML(r.stock)}</span></div></td>
      <td><span class="tf-tag">${escapeHTML(r.timeframe)}</span></td>
      <td><span class="badge ${trendBadgeClass(r.trend_bucket)}"><span class="stamp">${abbrevTrend(r.trend_bucket)}</span> ${escapeHTML(r.trend_bucket)}</span></td>
      <td class="mono strong">${fmtNum(r.last_close)}</td>
      <td>${fibChips(r, "bull")}</td>
      <td>${fibChips(r, "bear")}</td>
      <td class="mono">${formatDate(r.last_date)}</td>
    `;
    tr.addEventListener("click", () => toggleExpand("dow", id));
    frag.appendChild(tr);
    if (EXPANDED.dow.has(id)) frag.appendChild(buildDowExpand(r));
  });
  body.appendChild(frag);
}

