function signalChips(r) {
  const items = [
    [r.bullish_momentum, "BM", "bull"],
    [r.bearish_momentum, "BRM", "bear"],
    [r.bullish_swing, "BS", "bull"],
    [r.bearish_swing, "BRS", "bear"]
  ];
  return `<div class="chipset">${items.map(([on,label,side]) => `<span class="signal-dot ${on ? `on ${side}` : ""}" title="${label}"></span>`).join("")}</div>`;
}

function toggleExpand(scope, id) {
  if (EXPANDED[scope].has(id)) EXPANDED[scope].delete(id);
  else EXPANDED[scope].add(id);
  renderTable(scope);
}

/* =========================================================
   TICKER
   ========================================================= */
function renderTicker(scope) {
  const track = document.getElementById("tickerTrack");
  if (!track) return;
  const rows = scope === "dow" ? getDowFiltered() : getWgatFiltered();
  const items = rows.slice(0, 40).map(r => {
    const label = scope === "dow" ? r.stock : r.stock;
    const value = scope === "dow" ? r.trend_bucket : r.category_1;
    const cls = scope === "dow" ? trendBadgeClass(r.trend_bucket) : wgatBadgeClass(r.category_1);
    return `<span class="ticker-chip ${cls}"><span class="lbl">${escapeHTML(label)}</span><span class="val">${escapeHTML(value)}</span></span>`;
  });
  const html = items.length ? items.join("") : `<span class="ticker-chip neutral"><span class="lbl">Scanner</span><span class="val">No matching rows</span></span>`;
  track.innerHTML = html + html;
}

/* =========================================================
   HELPERS
   ========================================================= */
function renderTable(scope) {
  if (scope === "dow") renderDow();
  else renderWgat();
}

function trendBadgeClass(bucket = "") {
  if (bucket === "Uptrend" || bucket === "Reversal To Uptrend") return "bull";
  if (bucket === "Downtrend" || bucket === "Reversal To Downtrend") return "bear";
  return "neutral";
}

function wgatBadgeClass(cat = "") {
  if (cat.includes("Uptrend") || cat.includes("Aligned Up") || cat.includes("Going Up")) return "bull";
  if (cat.includes("Down") || cat.includes("Aligned Down")) return "bear";
  return "neutral";
}

function abbrevTrend(bucket) {
  const map = { "Uptrend":"UP", "Downtrend":"DN", "Reversal To Uptrend":"REV↑", "Reversal To Downtrend":"REV↓", "Triangle / Sideways":"SIDE" };
  return map[bucket] || "—";
}

function fibChips(r, side) {
  return `<div class="chipset">${FIBS.map(([k,l]) => {
    const on = r[`${k}_${side}`] === true;
    const price = r[`${k}_${side === "bull" ? "up" : "down"}`];
    return `<span class="chip-dot ${on ? `on ${side}` : ""}" title="${l} ${side} ${price != null ? "@ " + fmtNum(price) : "—"}">${l}</span>`;
  }).join("")}</div>`;
}

function fmtNum(v, decimals = 2) {
  if (v == null || !Number.isFinite(Number(v))) return "—";
  return Number(v).toLocaleString("en-IN", { minimumFractionDigits: decimals, maximumFractionDigits: decimals });
}

function formatDate(v) {
  if (!v) return "—";
  const d = new Date(v);
  return Number.isNaN(d.getTime()) ? String(v) : d.toLocaleDateString("en-IN", { year:"numeric", month:"short", day:"2-digit" });
}

function emptyState(title, sub) {
  return `<div class="icon">⌁</div><h3>${escapeHTML(title)}</h3><p>${escapeHTML(sub)}</p>`;
}

function loadingState() { return `<div class="icon">…</div><h3>Loading scan data</h3><p>Please wait.</p>`; }

function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>'"]/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;","'":"&#39;","\"":"&quot;"}[c]));
}
